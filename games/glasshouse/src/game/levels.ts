export const seasonOf = (i: number): Season => FLOWERS[i].season;
export const levelName = (i: number) => `${t(`season.${seasonOf(i)}`)} ${(i % 6) + 1}`;

/** 그 판에서 처음 나오는 규칙 안내(판 위 한 줄) */
export const TIPS: Partial<Record<number, MessageKey>> = { 0: 'tip.l1', 1: 'tip.l2', 3: 'tip.l4', 6: 'tip.l7', 12: 'tip.l13', 18: 'tip.l19' };

/**
 * 화분마다 피울 꽃: 그 판의 꽃과 습성이 같으면 그 꽃, 아니면 앞 판들에서 가장 최근에 핀 같은 습성의 꽃
 * (그 판에서 처음 나오는 습성이 없게 판을 골랐지만, 없으면 같은 습성의 첫 꽃)
 */
export function speciesFor(level: number, habits: readonly Habit[]): FlowerId[] {
  const main = FLOWER[LEVELS[level].flower];
  return habits.map((h) => {
    if (h === main.habit) return main.id;
    for (let i = level - 1; i >= 0; i--) if (FLOWERS[i].habit === h) return FLOWERS[i].id;
    return FLOWERS.find((f) => f.habit === h)!.id;
  });
}

/** 계절마다 처음 나오는 요소 안내(오늘의 정원 판 위 한 줄) */
export const SEASON_TIP: Record<Season, MessageKey> = { spring: 'tip.l4', summer: 'tip.l7', autumn: 'tip.l13', winter: 'tip.l19' };

/**
 * 오늘의 정원 화분마다 피울 꽃: 그 판 계절의 같은 습성 꽃 가운데 이미 도감에 연 꽃을 먼저(아직 못 본 꽃을 미리 보이지 않게),
 * 날마다 돌아가며 고른다. opened 는 도감에 열린 판 번호
 */
export function dailySpecies(season: Season, habits: readonly Habit[], day: number, opened: (i: number) => boolean): FlowerId[] {
  return habits.map((h, k) => {
    const pools = [
      FLOWERS.filter((f, i) => f.habit === h && f.season === season && opened(i)),
      FLOWERS.filter((f, i) => f.habit === h && opened(i)),
      FLOWERS.filter((f) => f.habit === h && f.season === season),
      FLOWERS.filter((f) => f.habit === h),
    ];
    const pool = pools.find((p) => p.length)!;
    return pool[(((day + k * 7) % pool.length) + pool.length) % pool.length].id;
  });
}
