const dictionaries: Record<Lang, Record<MessageKey, string>> = { ko, en };
let current: Lang = 'ko';

export function setLang(lang: Lang): void {
  current = lang;
  document.documentElement.lang = lang;
  document.title = dictionaries[lang]['app.title'];
}

export function getLang(): Lang {
  return current;
}

export function detectLang(): Lang {
  try {
    return navigator.language.toLowerCase().startsWith('ko') ? 'ko' : 'en';
  } catch {
    return 'ko';
  }
}

export function t(key: MessageKey, params: Record<string, string | number> = {}): string {
  return dictionaries[current][key].replace(/\{(\w+)\}/g, (_, name: string) => {
    const value = params[name];
    return typeof value === 'number' ? value.toLocaleString() : String(value ?? '');
  });
}

export function moleName(kind: MoleKind): string {
  return t(`mole.${kind}.name` as MessageKey);
}

export function moleDesc(kind: MoleKind): string {
  return t(`mole.${kind}.desc` as MessageKey);
}
