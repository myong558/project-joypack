export type MessageKey = keyof typeof MESSAGES.ko;
export const LANGS = Object.keys(MESSAGES) as Lang[];
/** 언어 선택 단추에 쓰는 이름. 어느 언어 화면에서든 그 언어 자체 표기로 보여준다 */
export const NAMES: Record<Lang, string> = { ko: '한국어', en: 'English' };

/** 저장된 선택이 없으면 기기 설정 언어를 따른다(조이필드 공통 Joyfield.deviceLang). 공통 설정(joyfield.lang)을 먼저, 없으면 예전 키 */
function detectLang(): Lang {
  const saved = Joyfield.get('lang', LANG_KEY);
  return saved === 'ko' || saved === 'en' ? saved : Joyfield.deviceLang();
}

let lang: Lang = detectLang();

export function getLang(): Lang {
  return lang;
}

export function setLang(next: Lang): void {
  if (!LANGS.includes(next)) return;
  lang = next;
  Joyfield.set('lang', next, LANG_KEY);
}

function message(key: MessageKey): Message {
  return (MESSAGES[lang] as Record<string, Message>)[key] ?? (MESSAGES.ko as Record<string, Message>)[key];
}

/** 문구. 함수 문구는 params 로 만들고, 글자 문구는 {이름} 자리를 params 로 채운다 */
export function t(key: MessageKey, params: P = {}): string {
  const m = message(key);
  if (typeof m === 'function') return m(params);
  if (Array.isArray(m)) return m[0];
  return m.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? ''));
}

/** 결과 화면 운 문구 목록(단계마다 10개) */
export function luckLines(tier: string): string[] {
  const m = message(('luck.' + tier) as MessageKey);
  return Array.isArray(m) ? m : [];
}
